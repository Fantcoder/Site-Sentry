"""Report generation: JSON, Markdown, self-contained HTML, SARIF 2.1.0."""

from __future__ import annotations

import json
from datetime import datetime
from typing import Any

from sitesentry import __version__
from sitesentry.models import ScanResult, Severity

# ---------------------------------------------------------------------------
# Severity → SARIF level mapping
# ---------------------------------------------------------------------------
_SARIF_LEVEL: dict[Severity, str] = {
    Severity.critical: "error",
    Severity.high: "error",
    Severity.medium: "warning",
    Severity.low: "note",
    Severity.info: "none",
}

_GRADE_COLORS: dict[str, str] = {
    "A": "#2ecc71",
    "B": "#27ae60",
    "C": "#f39c12",
    "D": "#e67e22",
    "F": "#e74c3c",
}

_SEVERITY_EMOJI: dict[Severity, str] = {
    Severity.critical: "🔴",
    Severity.high: "🔴",
    Severity.medium: "🟠",
    Severity.low: "🟡",
    Severity.info: "ℹ️",
}


def _fmt_dt(dt: datetime | None) -> str:
    if dt is None:
        return "N/A"
    return dt.strftime("%Y-%m-%d %H:%M:%S UTC")


class ReportGenerator:
    """Generates reports in four formats from a ScanResult."""

    # ------------------------------------------------------------------
    # JSON
    # ------------------------------------------------------------------

    @staticmethod
    def to_json(result: ScanResult) -> str:
        """Serialize to indented JSON."""
        return result.model_dump_json(indent=2)

    # ------------------------------------------------------------------
    # Markdown
    # ------------------------------------------------------------------

    @staticmethod
    def to_markdown(result: ScanResult) -> str:
        lines: list[str] = []
        lines.append("# SiteSentry Scan Report\n")
        lines.append("| Field | Value |")
        lines.append("|---|---|")
        lines.append(f"| Target | `{result.target_url}` |")
        lines.append(f"| Scan ID | `{result.scan_id}` |")
        lines.append(f"| Started | {_fmt_dt(result.started_at)} |")
        lines.append(f"| Completed | {_fmt_dt(result.completed_at)} |")
        lines.append(f"| Pages Crawled | {result.page_count} |")
        lines.append(f"| **Grade** | **{result.grade}** |")
        lines.append(f"| **Score** | **{result.score}/100** |")
        if result.has_incomplete_checks:
            lines.append("| ⚠️ Incomplete Checks | Yes – some checks errored |")
        lines.append("")

        # Score breakdown
        if result.breakdown:
            lines.append("## Score Breakdown\n")
            lines.append("| Check | Findings | Deduction |")
            lines.append("|---|---|---|")
            for bd in result.breakdown:
                lines.append(f"| {bd.check_id} | {bd.finding_count} | -{bd.capped_deduction} |")
            lines.append("")

        # Findings by severity
        all_findings = result.all_findings
        if not all_findings:
            lines.append("## ✅ No Findings\n")
            lines.append("No security issues were detected.\n")
        else:
            lines.append("## Findings\n")
            for severity in [
                Severity.critical,
                Severity.high,
                Severity.medium,
                Severity.low,
                Severity.info,
            ]:
                sev_findings = [f for f in all_findings if f.severity == severity]
                if not sev_findings:
                    continue
                emoji = _SEVERITY_EMOJI[severity]
                lines.append(f"### {emoji} {severity.value.title()} ({len(sev_findings)})\n")
                for f in sev_findings:
                    lines.append(f"#### [{f.check_id}] {f.title}\n")
                    lines.append(f"- **URL:** `{f.url}`")
                    lines.append(f"- **Evidence:** `{f.evidence}`")
                    lines.append(f"- **Explanation:** {f.explanation}")
                    lines.append(f"- **Fix:** {f.fix}")
                    lines.append("")

        # Errors
        if result.errors:
            lines.append("## Errors\n")
            for err in result.errors:
                lines.append(f"- {err}")
            lines.append("")

        lines.append(f"---\n*Generated by SiteSentry {__version__}*")
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # HTML (self-contained, no external CDN)
    # ------------------------------------------------------------------

    @staticmethod
    def to_html(result: ScanResult) -> str:
        grade_color = _GRADE_COLORS.get(result.grade, "#95a5a6")
        all_findings = result.all_findings

        finding_html_parts: list[str] = []
        for severity in [
            Severity.critical,
            Severity.high,
            Severity.medium,
            Severity.low,
            Severity.info,
        ]:
            sev_findings = [f for f in all_findings if f.severity == severity]
            if not sev_findings:
                continue
            emoji = _SEVERITY_EMOJI[severity]
            finding_html_parts.append(
                f"<h2>{emoji} {severity.value.title()} "
                f'<span class="count">({len(sev_findings)})</span></h2>'
            )
            for f in sev_findings:
                finding_html_parts.append(
                    f'<details class="finding sev-{severity.value}">'
                    f'<summary><span class="badge {severity.value}">'
                    f"{severity.value.upper()}</span> "
                    f"<strong>[{f.check_id}]</strong> {_esc(f.title)}</summary>"
                    f'<div class="finding-body">'
                    f"<p><strong>URL:</strong> <code>{_esc(f.url)}</code></p>"
                    f"<p><strong>Evidence:</strong> <code>{_esc(f.evidence)}</code></p>"
                    f"<p><strong>Explanation:</strong> {_esc(f.explanation)}</p>"
                    f"<p><strong>Fix:</strong> {_esc(f.fix)}</p>"
                    f"</div></details>"
                )

        findings_section = (
            "\n".join(finding_html_parts)
            if finding_html_parts
            else '<p class="clean">✅ No security issues detected.</p>'
        )

        breakdown_rows = "".join(
            f"<tr><td><code>{_esc(bd.check_id)}</code></td>"
            f"<td>{_esc(bd.check_title)}</td>"
            f"<td>{bd.finding_count}</td>"
            f"<td>-{bd.capped_deduction}</td></tr>"
            for bd in result.breakdown
        )

        return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>SiteSentry Report – {_esc(result.target_url)}</title>
<style>
  *, *::before, *::after {{ box-sizing: border-box; }}
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
          background: #f5f6fa; color: #2c3e50; margin: 0; padding: 20px; }}
  .container {{ max-width: 900px; margin: 0 auto; }}
  h1 {{ color: #2c3e50; border-bottom: 3px solid #3498db; padding-bottom: 10px; }}
  h2 {{ margin-top: 30px; }}
  .meta-grid {{ display: grid; grid-template-columns: auto 1fr; gap: 6px 16px;
               background: #fff; padding: 20px; border-radius: 8px;
               box-shadow: 0 2px 8px rgba(0,0,0,.08); margin-bottom: 20px; }}
  .meta-grid dt {{ font-weight: 600; color: #7f8c8d; }}
  .grade-badge {{ display: inline-block; background: {grade_color}; color: #fff;
                  font-size: 3rem; font-weight: 900; width: 90px; height: 90px;
                  line-height: 90px; text-align: center; border-radius: 12px;
                  float: right; margin: -10px 0 10px 20px; }}
  .score {{ font-size: 1.2rem; color: {grade_color}; font-weight: 700; }}
  table {{ width: 100%; border-collapse: collapse; background: #fff;
           border-radius: 8px; overflow: hidden;
           box-shadow: 0 2px 8px rgba(0,0,0,.08); margin-bottom: 20px; }}
  th {{ background: #3498db; color: #fff; padding: 10px 14px; text-align: left; }}
  td {{ padding: 8px 14px; border-bottom: 1px solid #ecf0f1; }}
  tr:last-child td {{ border-bottom: none; }}
  details.finding {{ background: #fff; border-radius: 6px; margin-bottom: 8px;
                      box-shadow: 0 1px 4px rgba(0,0,0,.08); overflow: hidden; }}
  details.finding > summary {{ padding: 12px 16px; cursor: pointer; list-style: none;
                               display: flex; align-items: center; gap: 10px; }}
  details.finding > summary::-webkit-details-marker {{ display: none; }}
  details.finding[open] > summary {{ border-bottom: 1px solid #ecf0f1; }}
  .finding-body {{ padding: 16px; }}
  .finding-body p {{ margin: 6px 0; }}
  .badge {{ display: inline-block; padding: 2px 8px; border-radius: 4px;
             font-size: 0.72rem; font-weight: 700; text-transform: uppercase; color: #fff; }}
  .badge.critical, .badge.high {{ background: #e74c3c; }}
  .badge.medium {{ background: #e67e22; }}
  .badge.low {{ background: #f39c12; color: #fff; }}
  .badge.info {{ background: #3498db; }}
  .count {{ color: #7f8c8d; font-weight: 400; font-size: 0.9em; }}
  .clean {{ font-size: 1.1rem; color: #2ecc71; font-weight: 600; }}
  code {{ background: #ecf0f1; padding: 1px 5px; border-radius: 3px; font-size: 0.88em; word-break: break-all; }}
  footer {{ margin-top: 40px; text-align: center; color: #95a5a6; font-size: 0.85rem; }}
  .incomplete-warn {{ background: #ffeaa7; border: 1px solid #fdcb6e; border-radius: 6px;
                       padding: 10px 16px; margin-bottom: 16px; }}
</style>
</head>
<body>
<div class="container">
  <h1>🔍 SiteSentry Scan Report</h1>
  {'<div class="incomplete-warn">⚠️ Some checks did not complete successfully. The grade may be optimistic.</div>' if result.has_incomplete_checks else ""}
  <div class="meta-grid">
    <div class="grade-badge">{_esc(result.grade)}</div>
    <dt>Target</dt><dd><code>{_esc(result.target_url)}</code></dd>
    <dt>Scan ID</dt><dd><code>{_esc(result.scan_id)}</code></dd>
    <dt>Started</dt><dd>{_fmt_dt(result.started_at)}</dd>
    <dt>Completed</dt><dd>{_fmt_dt(result.completed_at)}</dd>
    <dt>Pages Crawled</dt><dd>{result.page_count}</dd>
    <dt>Score</dt><dd class="score">{result.score}/100</dd>
    <dt>Total Findings</dt><dd>{len(all_findings)}</dd>
  </div>

  <h2>Score Breakdown</h2>
  <table>
    <thead><tr><th>Check ID</th><th>Check</th><th>Findings</th><th>Deduction</th></tr></thead>
    <tbody>{breakdown_rows}</tbody>
  </table>

  <h2>Findings</h2>
  {findings_section}

  <footer>Generated by SiteSentry {__version__} &middot; Passive security scanner</footer>
</div>
</body>
</html>"""

    # ------------------------------------------------------------------
    # SARIF 2.1.0
    # ------------------------------------------------------------------

    @staticmethod
    def to_sarif(result: ScanResult) -> str:
        """Produce a SARIF 2.1.0 document."""
        from sitesentry.checks.registry import ALL_CHECKS

        rules: list[dict[str, Any]] = [
            {
                "id": cls.id,
                "name": cls.id.replace("-", "_").title().replace("_", ""),
                "shortDescription": {"text": cls.title},
                "help": {"text": f"SiteSentry check: {cls.title}"},
            }
            for cls in ALL_CHECKS
        ]

        sarif_results: list[dict[str, Any]] = []
        for f in result.all_findings:
            sarif_results.append(
                {
                    "ruleId": f.check_id,
                    "level": _SARIF_LEVEL.get(f.severity, "note"),
                    "message": {
                        "text": f"{f.title}\n\nEvidence: {f.evidence}\n\n"
                        f"Explanation: {f.explanation}\n\nFix: {f.fix}"
                    },
                    "locations": [
                        {
                            "physicalLocation": {
                                "artifactLocation": {"uri": f.url},
                            }
                        }
                    ],
                    "properties": {
                        "severity": f.severity.value,
                        "checkId": f.check_id,
                    },
                }
            )

        doc: dict[str, Any] = {
            "$schema": (
                "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/"
                "main/sarif-2.1/schema/sarif-schema-2.1.0.json"
            ),
            "version": "2.1.0",
            "runs": [
                {
                    "tool": {
                        "driver": {
                            "name": "SiteSentry",
                            "version": __version__,
                            "informationUri": "https://github.com/Fantcoder/Site-Sentry",
                            "rules": rules,
                        }
                    },
                    "results": sarif_results,
                    "properties": {
                        "scanId": result.scan_id,
                        "targetUrl": result.target_url,
                        "grade": result.grade,
                        "score": result.score,
                    },
                }
            ],
        }
        return json.dumps(doc, indent=2)


def _esc(text: str) -> str:
    """Minimal HTML escaping."""
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )
